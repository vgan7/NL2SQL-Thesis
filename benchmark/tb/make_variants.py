#!/usr/bin/env python3
import copy
import subprocess
from pathlib import Path

import yaml

from mapping import COLS, ENCODE, SRC_TABLE, VALUES, VIEW, to_opaque, view_ddl

TAG = "prompt-v2.2-frozen"
HERE = Path(__file__).resolve().parent


def frozen(path):
    out = subprocess.run(["git", "show", f"{TAG}:{path}"], capture_output=True,
                         text=True, check=True, cwd=HERE)
    return yaml.safe_load(out.stdout)


def dump(obj, name, header):
    with open(HERE / name, "w", encoding="utf-8") as f:
        f.write(header)
        yaml.safe_dump(obj, f, allow_unicode=True, sort_keys=False, width=100)
    print("wrote", name)


def opaque_domain(dom):
    d = copy.deepcopy(dom)
    ds = d["dataset"]
    ds["time_anchor"] = {"table": VIEW, "column": COLS[ds["time_anchor"]["column"]]}

    t = d["tables"].pop(SRC_TABLE)
    cols = {}
    for orig, desc in t["columns"].items():
        desc = to_opaque(desc, prose=True)
        if orig in VALUES:
            legend = ", ".join(f"{code} = {name}" for name, code in VALUES[orig].items())
            desc += f" (codes: {legend})"
        cols[COLS[orig]] = desc
    t["columns"] = cols
    t["values"] = {COLS[c]: [ENCODE[v] for v in vals] for c, vals in t["values"].items()}
    d["tables"] = {VIEW: t}

    syn = {}
    for term, target in d["synonyms"].items():
        if target in COLS:
            syn[term] = COLS[target]
        else:
            val, col = target.rsplit(" (", 1)
            col = col.rstrip(")")
            syn[term] = f"{ENCODE[val]} ({COLS[col]})"
    d["synonyms"] = syn

    d["rules"] = [to_opaque(r, prose=True) for r in d["rules"]]
    d["examples"] = [{"q": e["q"], "sql": to_opaque(e["sql"])} for e in d["examples"]]
    d["answer_rules"] = [to_opaque(r, prose=True) for r in d["answer_rules"]]
    d["column_nouns"] = {COLS.get(k, k): v for k, v in d["column_nouns"].items()}
    return d


def nodesc_domain(opaque):
    d = copy.deepcopy(opaque)
    d["tables"] = {VIEW: {}}
    d.pop("synonyms", None)
    return d


def bare_domain(dom, table, ts_col):
    ds = dom["dataset"]
    return {
        "dataset": {"name": "database", "static": ds["static"],
                    "time_anchor": {"table": table, "column": ts_col}},
        "tables": {table: {}},
    }


def opaque_questions(qs):
    out = copy.deepcopy(qs)
    for q in out:
        q["gold_sql"] = to_opaque(q["gold_sql"])
        for turn in q.get("history") or []:
            if "sql" in turn:
                turn["sql"] = to_opaque(turn["sql"])
    return out


if __name__ == "__main__":
    note = f"# GENERATED by benchmark/tb/make_variants.py from {TAG} — do not edit by hand.\n"
    (HERE / "view_hist_1m.sql").write_text(note.replace("#", "--", 1) + view_ddl(), encoding="utf-8")
    print("wrote view_hist_1m.sql")

    dom = frozen("nl2sql-api/domain.yaml")
    dump(opaque_domain(dom), "domain_opaque.yaml", note)
    dump(nodesc_domain(opaque_domain(dom)), "domain_opaque_nodesc.yaml", note)
    dump(bare_domain(dom, VIEW, COLS["ts"]), "domain_opaque_bare.yaml", note)
    dump(bare_domain(dom, SRC_TABLE, "ts"), "domain_clear_bare.yaml", note)

    dump(opaque_questions(frozen("benchmark/questions.yaml")), "questions_opaque.yaml", note)
    dump(opaque_questions(frozen("benchmark/questions_mid.yaml")), "questions_mid_opaque.yaml", note)
