#!/usr/bin/env python3
import copy
import re
import subprocess
from pathlib import Path

import yaml

from translations import EXAMPLES, HISTORY, NOISY_CATEGORIES, NOTES, Q, RULE_PHRASES, SYNONYMS

TAG = "prompt-v2.2-frozen"
HERE = Path(__file__).resolve().parent
GREEK = re.compile(r"[Ͱ-Ͽἀ-῿]")


def frozen(path):
    out = subprocess.run(["git", "show", f"{TAG}:{path}"], capture_output=True,
                         text=True, check=True, cwd=HERE)
    return yaml.safe_load(out.stdout)


def dump(obj, name):
    with open(HERE / name, "w", encoding="utf-8") as f:
        f.write(f"# GENERATED by benchmark/lang/make_en.py from {TAG} — do not edit by hand.\n")
        yaml.safe_dump(obj, f, allow_unicode=True, sort_keys=False, width=100)
    print("wrote", name)


def en_domain(dom):
    d = copy.deepcopy(dom)
    assert set(d["synonyms"]) == set(SYNONYMS), set(d["synonyms"]) ^ set(SYNONYMS)
    d["synonyms"] = {SYNONYMS[k]: v for k, v in d["synonyms"].items()}
    rules = []
    for r in d["rules"]:
        for el, en in RULE_PHRASES.items():
            r = r.replace(el, en)
        assert not GREEK.search(r), f"Greek left in rule: {r}"
        rules.append(r)
    d["rules"] = rules
    for e in d["examples"]:
        e["q"] = EXAMPLES[e["q"]]
    return d


def en_questions(qs):
    out = copy.deepcopy(qs)
    for q in out:
        q["question_el"] = q["question"]
        q["question"] = Q[q["id"]]
        for turn in q.get("history") or []:
            turn["question"] = HISTORY[turn["question"]]
    return out


if __name__ == "__main__":
    dump(en_domain(frozen("nl2sql-api/domain.yaml")), "domain_en.yaml")
    rows = []
    for src, dst in (("benchmark/questions.yaml", "questions_en.yaml"),
                     ("benchmark/questions_mid.yaml", "questions_mid_en.yaml")):
        qs = frozen(src)
        missing = [q["id"] for q in qs if q["id"] not in Q]
        assert not missing, f"untranslated: {missing}"
        dump(en_questions(qs), dst)
        rows += [(q["id"], q["category"], q["question"], Q[q["id"]]) for q in qs]
    lines = ["# Translation review (Greek -> English)\n",
             "Gold SQL is identical; only the question text changes. "
             "**noisy** = typo/malformed/paraphrase, reported separately. ✎ = translator's note below.\n",
             "| id | group | Greek | English |", "|---|---|---|---|"]
    for i, cat, el, en in rows:
        grp = "noisy" if cat in NOISY_CATEGORIES else "clean"
        lines.append(f"| {i}{' ✎' if i in NOTES else ''} | {grp} | {el} | {en} |")
    lines += ["\n## Translator's notes\n"] + [f"- **{k}**: {v}" for k, v in NOTES.items()]
    (HERE / "review_translation.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("wrote review_translation.md")
